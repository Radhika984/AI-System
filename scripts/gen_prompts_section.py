"""Regenerate the verbatim product-prompt section of PROMPTS.md from the code
(backend/app/llm/prompts.py), so the document can never drift from what runs.

The rendered user-message examples (judge case, edit repair, batch separators) are captured from an
OFFLINE replay of the real pipeline (LLM_OFFLINE=1: cache only, the API is never called), so they are
the exact strings the code sends. Only lines longer than MAX_LINE characters (raw HTML) are shortened,
and every shortened line says how many characters were left out.

Replaces everything between <!-- BEGIN:PRODUCT_PROMPTS --> and <!-- END:PRODUCT_PROMPTS -->.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ["LLM_OFFLINE"] = "1"  # must be set before app.config is imported; replay never calls the API

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app import normalize as N, pipeline, taxonomy  # noqa: E402
from app.llm import prompts as P  # noqa: E402
from app.llm.client import LLMClient  # noqa: E402

BEGIN, END = "<!-- BEGIN:PRODUCT_PROMPTS -->", "<!-- END:PRODUCT_PROMPTS -->"
R004_QID = "68e870ef42c06737d6e565c4"
MAX_LINE = 300


def fence(text: str) -> str:
    return "````text\n" + text.strip("\n") + "\n````"


def shorten(text: str) -> str:
    out = []
    for ln in text.splitlines():
        if len(ln) > MAX_LINE:
            ln = ln[:MAX_LINE] + f" …[{len(ln) - MAX_LINE} more characters of this line omitted here; sent in full]"
        out.append(ln)
    return "\n".join(out)


def replay_calls() -> list[dict]:
    """Run the real pipeline offline and record every LLM request it makes (and whether it was a cache hit)."""
    client = LLMClient()
    calls, original = [], client.complete_json

    def record(**kw):
        before = client.stats["cache_hits"]
        try:
            return original(**kw)
        finally:
            calls.append({"prompt_version": kw["prompt_version"], "user": kw["user"],
                          "cache_hit": client.stats["cache_hits"] > before})

    client.complete_json = record
    pipeline.run(client=client, log=lambda *a: None)
    assert client.stats["calls"] == 0, "the prompt generator must never call the API"
    return calls


def build() -> str:
    q = N.questions_by_id()[R004_QID]  # R004's question, as a concrete example
    calls = replay_calls()
    judge_batch = next(c for c in calls if c["prompt_version"].startswith("judge") and R004_QID in c["user"] and c["cache_hit"])
    r004_case = next("########## CASE C" + s for s in judge_batch["user"].split("########## CASE C")[1:] if R004_QID in s)
    solver_batch = next(c for c in calls if c["prompt_version"].startswith("solverA") and c["cache_hit"])
    fix = next(c for c in calls if c["prompt_version"].startswith("editfix") and c["cache_hit"])
    parts = [
        BEGIN,
        "_Auto-generated by `scripts/gen_prompts_section.py` from `backend/app/llm/prompts.py`, plus an offline replay "
        "of the pipeline (cache only, 0 API calls) for the rendered user messages. Do not edit by hand._",
        "",
        f"### Solver A — system prompt (`{P.SOLVER_A_VERSION}`)",
        fence(P.SOLVER_A_SYSTEM),
        f"### Solver B — system prompt (`{P.SOLVER_B_VERSION}`)",
        fence(P.SOLVER_B_SYSTEM),
        f"### Batch suffix appended to both solver prompts (`{P.SOLVER_BATCH_SUFFIX_VERSION}`)",
        fence(P.SOLVER_BATCH_SUFFIX),
        "### Solver user message (template output for R004's question — note: no key, no solution, no comment)",
        fence(P.solver_user(N.question_view(q))),
        f"### Judge — system prompt (`{P.JUDGE_VERSION}`; taxonomy block is rendered from `data/taxonomy.json`)",
        fence(P.judge_system(taxonomy.load())),
        "### Batch suffix appended to the judge prompt (`batch-v1`)",
        fence(P.JUDGE_BATCH_SUFFIX),
        "### Batch separators (`solver_batch_user()` / `judge_batch_user()`)",
        "Each batched request joins its items with a blank line, and each item starts with a separator line. "
        "First lines of the real batched requests:",
        fence(solver_batch["user"].splitlines()[0] + "\n" + judge_batch["user"].splitlines()[0]),
        "### Judge user message (R004's case, as sent inside its real batched request)",
        "Built by `prompts.judge_user(judge.build_packet(...))`. Captured from the offline replay; this exact request "
        f"is a cache hit, so it is byte-for-byte what was sent. Lines over {MAX_LINE} characters (raw HTML) are shortened "
        "here and marked.",
        fence(shorten(r004_case)),
        f"### Edit repair — system prompt (`{P.EDIT_FIX_VERSION}`; used once when the guard rejects an edit)",
        fence(P.EDIT_FIX_SYSTEM),
        "### Edit repair — user message (R009/R010's rejected option edit; real request, a cache hit)",
        f"Built by `prompts.edit_fix_user(...)`. Lines over {MAX_LINE} characters are shortened here and marked.",
        fence(shorten(fix["user"])),
        END,
    ]
    return "\n".join(parts)


def main() -> int:
    path = ROOT / "PROMPTS.md"
    text = path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("markers not found in PROMPTS.md")
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    path.write_text(head + build() + tail, encoding="utf-8", newline="\n")
    print("PROMPTS.md product-prompt section regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
