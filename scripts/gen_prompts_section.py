"""Regenerate the verbatim product-prompt section of PROMPTS.md from the code
(backend/app/llm/prompts.py), so the document can never drift from what runs.

Replaces everything between <!-- BEGIN:PRODUCT_PROMPTS --> and <!-- END:PRODUCT_PROMPTS -->.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app import normalize as N, taxonomy  # noqa: E402
from app.llm import prompts as P  # noqa: E402

BEGIN, END = "<!-- BEGIN:PRODUCT_PROMPTS -->", "<!-- END:PRODUCT_PROMPTS -->"


def fence(text: str) -> str:
    return "````text\n" + text.strip("\n") + "\n````"


def build() -> str:
    q = N.questions_by_id()["68e870ef42c06737d6e565c4"]  # R004's question, as a concrete example
    parts = [
        BEGIN,
        "_Auto-generated by `scripts/gen_prompts_section.py` from `backend/app/llm/prompts.py`. Do not edit by hand._",
        "",
        f"### Solver A — system prompt (`{P.SOLVER_A_VERSION}`)",
        fence(P.SOLVER_A_SYSTEM),
        f"### Solver B — system prompt (`{P.SOLVER_B_VERSION}`)",
        fence(P.SOLVER_B_SYSTEM),
        f"### Batch suffix appended to both solver prompts (`{P.SOLVER_BATCH_SUFFIX_VERSION}`)",
        fence(P.SOLVER_BATCH_SUFFIX),
        "### Solver user message (template output for R004's question — note: no key, no solution, no comment)",
        fence(P.solver_user(N.question_view(q))),
        f"### Judge — system prompt (`{P.JUDGE_VERSION}`; taxonomy block is rendered from `data/taxonomy.json`)",
        fence(P.judge_system(taxonomy.load())),
        "### Batch suffix appended to the judge prompt (`batch-v1`)",
        fence(P.JUDGE_BATCH_SUFFIX),
        "### Judge user message",
        "Built by `prompts.judge_user(packet)`: question id/type/subject, stem, options, `STORED_ANSWER_STRING`, "
        "stored solution text, RAW HTML of `question` and `solution` (edit anchors), `errorHistory`, deterministic "
        "pre-check flags, both blind solves + agreement summary, then each report as "
        "`<student_comment>{html-escaped comment}</student_comment>`. Full example packets are in `cache/llm/`.",
        "",
        f"### Edit repair — system prompt (`{P.EDIT_FIX_VERSION}`; used once when the guard rejects an edit)",
        fence(P.EDIT_FIX_SYSTEM),
        END,
    ]
    return "\n".join(parts)


def main() -> int:
    path = ROOT / "PROMPTS.md"
    text = path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("markers not found in PROMPTS.md")
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    path.write_text(head + build() + tail, encoding="utf-8")
    print("PROMPTS.md product-prompt section regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
